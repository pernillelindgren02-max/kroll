import type { KnittingPattern, PatternSection, PatternSize } from '../../types/models'

function garmentSizes(
  labels: string[],
  chest: number[],
  length: number[],
  sleeve: number[] | undefined,
  easeMin: number,
  easeMax: number,
): PatternSize[] {
  return labels.map((label, i) => ({
    id: `size-${label.toLowerCase()}`,
    label: t(label, label),
    chestCm: chest[i],
    lengthCm: length[i],
    sleeveLengthCm: sleeve?.[i],
    bodyBustMinCm: chest[i] - easeMax,
    bodyBustMaxCm: chest[i] - easeMin,
  }))
}

